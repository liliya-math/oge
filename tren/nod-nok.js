function gen1() {
  var a = rnd(3, 12), k = rnd(3, 9);
  if (rnd(0, 1) === 0) {
    return { q: '<p>Выпиши кратные числа ' + a + ' по порядку, начиная с самого числа ' + a + '. Какое число стоит на ' + k + '-м месте?</p>', input: rows(R.int('Ответ', 'x')),
      check: function (v) { return v.x === a * k ? 'ok' : 'wrong'; },
      tag: function (v) { if (v.x === a + k) return 'added'; if (v.x % a === 0) return 'place'; return 'not-multiple'; },
      sol: { x: a * k }, hint: 'Кратные числа ' + a + ': ' + mults(a, k) + '. На ' + k + '-м месте стоит ' + a + ' · ' + k + ' = ' + (a * k) + '.' };
  }
  var m = a * k, d = 0, i;
  for (i = 2; i < a; i++) if (a % i === 0) { d = i; break; }
  var fourth = d ? [d, String(d), 'divisor'] : [m + 2, String(m + 2), 'not-multiple'];
  return { q: '<p>Какое из чисел кратно числу ' + a + '?</p>',
    input: choice([[m, String(m)], [m + 1, String(m + 1), 'not-multiple'], [m - 1, String(m - 1), 'not-multiple'], fourth]), ans: m,
    hint: 'Кратное числа ' + a + ' делится на ' + a + ' без остатка: ' + m + ' : ' + a + ' = ' + k + '.' };
}

function gen2() {
  var P = pair(40, 1, 4), a = P.a, b = P.b, L = P.L, ok = L * rnd(1, 2), x, y, z;
  do { x = a * rnd(2, 9); } while (x % b === 0);
  do { y = b * rnd(2, 9); } while (y % a === 0);
  do { z = rnd(Math.max(a, b) + 1, 2 * L); } while (z % a === 0 || z % b === 0);
  return { q: '<p>Какое из чисел является общим кратным чисел ' + a + ' и ' + b + '?</p>',
    input: choice([[ok, String(ok)], [x, String(x), 'one-only'], [y, String(y), 'one-only'], [z, String(z), 'not-common']]), ans: ok,
    hint: 'Общее кратное делится и на ' + a + ', и на ' + b + ': ' + ok + ' : ' + a + ' = ' + (ok / a) + ', ' + ok + ' : ' + b + ' = ' + (ok / b) + '.' };
}

function nokTag(a, b, G, L) {
  return function (v) {
    if (v.x === G) return 'gcd-instead';
    if (v.x === a * b && a * b !== L) return 'product';
    if (v.x > 0 && v.x % a === 0 && v.x % b === 0) return 'not-least';
    return 'not-common';
  };
}

