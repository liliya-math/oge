function nw(s) { return '<span class="nw">' + s + '</span>'; }
function tbl(rows) { return '<table class="tbl">' + rows.map(function (r) { return '<tr>' + r.map(function (c, i) { return '<td' + (i === 0 ? ' class="h"' : '') + '>' + c + '</td>'; }).join('') + '</tr>'; }).join('') + '</table>'; }
function choice(list, shuf) {
  var o = list.map(function (a) { return { v: String(a[0]), html: a[1], tag: a[2] || '' }; });
  return { type: 'choice', options: shuf === false ? o : shuffle(o) };
}
function rows() { return { type: 'rows', rows: Array.prototype.slice.call(arguments) }; }
var R = { int: function (l, k) { return { label: l, kind: 'int', key: k }; } };
function ask(q, opts, ans, ok, no) { return { q: q, opts: opts, ans: ans, ok: ok, no: no }; }
function cpair(lo, hi) { var p, q; do { p = rnd(lo, hi); q = rnd(lo, hi); } while (p === q || gcd(p, q) !== 1); return [p, q]; }
/* пара a = g·p, b = g·q, p и q взаимно простые и больше 1: ни одно число не делится на другое */
function pair(maxv, gmin, gmax) {
  var g, pq, a, b;
  do { g = rnd(gmin, gmax); pq = cpair(2, 9); a = g * pq[0]; b = g * pq[1]; } while (a > maxv || b > maxv);
  return { a: a, b: b, G: gcd(a, b), L: lcm(a, b) };
}
function factors(n) { var f = [], d = 2; while (n > 1) { while (n % d === 0) { f.push(d); n /= d; } d++; } return f; }
function fs(list) { return list.join(' · '); }
function nod(a, b) { return nw('НОД(' + a + '; ' + b + ')'); }
function nok(a, b) { return nw('НОК(' + a + '; ' + b + ')'); }
function mults(a, n) { var s = []; for (var i = 1; i <= n; i++) s.push(a * i); return s.join(', '); }

