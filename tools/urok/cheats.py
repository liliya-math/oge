"""Шпаргалки уроков. Блок = часть урока, 'from' — номер первого экрана блока.
Каждый элемент: подпись (n) и/или формула (f, всегда отдельной строкой) и/или готовый html (r, например таблица).
Дроби и корни пишем через F() и R(): дробь всегда с горизонтальной чертой."""
from lesson_content import F, R

def _it(x):
    if isinstance(x, dict): return x
    if isinstance(x, tuple):
        d = {'n': x[0]}
        if len(x) > 1 and x[1]: d['f'] = x[1]
        if len(x) > 2 and x[2]: d['r'] = x[2]
        return d
    return {'n': x}

def _b(t, frm, *items): return {'from': frm, 't': t, 'items': [_it(i) for i in items]}

def tab(head, rows):
    h = ''.join(f'<th>{x}</th>' for x in head)
    r = ''.join('<tr>' + ''.join(f'<td>{c}</td>' for c in row) + '</tr>' for row in rows)
    return f'<table class="cst"><tr>{h}</tr>{r}</table>'

