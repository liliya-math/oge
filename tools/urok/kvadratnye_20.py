def roots(a, b, c):
    D = b * b - 4 * a * c
    if D < 0: return []
    if D == 0: return [-b / (2 * a)]
    s = math.sqrt(D)
    return sorted([(-b - s) / (2 * a), (-b + s) / (2 * a)])

