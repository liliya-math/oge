T = []
def info(kick, body='', h=None, box=None, say=None, cp=False, rev=None, id=None):
    d = {'kind': 'info', 'kick': kick, 'body': body}
    if h: d['h'] = h
    if box: d['box'] = box
    if say: d['say'] = say
    if rev: d['rev'] = {'btn': rev[0], 'html': rev[1]}
    if cp: d['cp'] = True
    if id: d['id'] = id
    T.append(d)

def widget(kick, key, h=None, cp=False, id=None):
    d = {'kind': 'widget', 'kick': kick, 'key': key}
    if h: d['h'] = h
    if cp: d['cp'] = True
    if id: d['id'] = id
    T.append(d)

def q(type_, text, a, why, hint, opts=None, back=None, fin=False, cp=False, note=None, wide=False, id=None):
    d = {'kind': 'q', 'type': type_, 'q': text, 'a': a, 'why': why, 'h': hint if isinstance(hint, list) else [hint]}
    if opts: d['opts'] = opts
    if back: d['back'] = back
    if fin: d['fin'] = True
    if cp: d['cp'] = True
    if note: d['note'] = note
    if wide: d['wide'] = True
    if id: d['id'] = id
    T.append(d)

