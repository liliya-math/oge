def fig_semi():
    O, r = (160, 160), 130
    a = math.radians(55)
    Pm = (O[0] + r * math.cos(a), O[1] - r * math.sin(a))
    g = _ln((20, 160), (300, 160)) + _ln((160, 20), (160, 160), 'gr')
    g += '<path d="M 30 160 A 130 130 0 0 1 290 160" class="ln" style="fill:none"/>'
    g += _ln(O, Pm, 'acc')
    g += _ln(Pm, (Pm[0], 160), 'ln', 'stroke-dasharray="5 4"')
    g += f'<circle cx="{Pm[0]:.1f}" cy="{Pm[1]:.1f}" r="5" class="dot"/>'
    g += f'<path d="M {O[0]+30} 160 A 30 30 0 0 0 {O[0]+30*math.cos(a):.1f} {O[1]-30*math.sin(a):.1f}" class="acc" style="stroke-width:2"/>'
    g += _t(O[0] + 44, 148, 'α', 'tm') + _t(Pm[0] + 14, Pm[1] - 8, 'M(x; y)')
    g += _t(30, 180, '−1', 'tm') + _t(160, 180, '0', 'tm') + _t(290, 180, '1', 'tm')
    g += _t(Pm[0] + 12, (Pm[1] + 160) / 2 + 4, 'y', 'tx', 'start') + _t((O[0] + Pm[0]) / 2, 176, 'x', 'tx')
    return fig(320, 190, g, 'Полуокружность радиуса 1')

def tbl(head, rows):
    h = ''.join(f'<th>{x}</th>' for x in head)
    r = ''.join('<tr>' + ''.join(f'<td>{c}</td>' for c in row) + '</tr>' for row in rows)
    return f'<div class="tblw"><table><tr>{h}</tr>{r}</table></div>'

