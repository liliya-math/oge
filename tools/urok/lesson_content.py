def fig_height():
    A, B, Cp = (30, 170), (270, 170), (170, 40)
    Hf = (170, 170)
    g = _ln(A, B) + _ln(A, Cp) + _ln(B, Cp) + _ln(Cp, Hf, 'acc', 'stroke-dasharray="6 4"')
