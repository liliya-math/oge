# ---------- рисунки (SVG, классы шаблона: ln, acc, tx, tm, dot) ----------
def fig(w, h, inner, cap=''):
    c = f'<div class="gcap">{cap}</div>' if cap else ''
    return f'<div class="fig"><svg viewBox="0 0 {w} {h}" width="{w}" role="img" aria-label="Чертёж">{inner}</svg></div>{c}'

def _t(x, y, s, cls='tx', anchor='middle'):
    return f'<text x="{x:.1f}" y="{y:.1f}" class="{cls}" text-anchor="{anchor}">{s}</text>'

def _ln(p, q, cls='ln', extra=''):
    return f'<line x1="{p[0]:.1f}" y1="{p[1]:.1f}" x2="{q[0]:.1f}" y2="{q[1]:.1f}" class="{cls}" {extra}/>'

def tri_sas(a, b, Cd, la='a', lb='b', lc='c', lang='C', W=330, H_=210, hl=True):
    """Треугольник: C — вершина слева внизу, CB = a вдоль оси, CA = b под углом C."""
    th = math.radians(Cd)
    pts = {'C': (0.0, 0.0), 'B': (a, 0.0), 'A': (b * math.cos(th), b * math.sin(th))}
    xs = [p[0] for p in pts.values()]; ys = [p[1] for p in pts.values()]
    w = max(xs) - min(xs); h = max(ys) - min(ys)
    pad = 38
    s = min((W - 2 * pad) / w, (H_ - 2 * pad) / h)
    ox = pad + (W - 2 * pad - w * s) / 2; oy = H_ - pad - ((H_ - 2 * pad) - h * s) / 2
    T = lambda p: (ox + (p[0] - min(xs)) * s, oy - (p[1] - min(ys)) * s)
    C, B, A = T(pts['C']), T(pts['B']), T(pts['A'])
    cen = ((C[0] + B[0] + A[0]) / 3, (C[1] + B[1] + A[1]) / 3)
    def out(p, d):
        vx, vy = p[0] - cen[0], p[1] - cen[1]; n = math.hypot(vx, vy) or 1
        return (p[0] + vx / n * d, p[1] + vy / n * d)
    g = _ln(C, B) + _ln(C, A) + _ln(A, B, 'acc' if hl else 'ln')
    # дуга угла C
    r = 24
    g += (f'<path d="M {C[0]+r:.1f} {C[1]:.1f} A {r} {r} 0 0 0 {C[0]+r*math.cos(th):.1f} {C[1]-r*math.sin(th):.1f}" '
          f'class="acc" style="stroke-width:2"/>')
    bis = (C[0] + 46 * math.cos(th / 2), C[1] - 46 * math.sin(th / 2))
    g += _t(bis[0], bis[1] + 5, lang, 'tm')
    for nm, p in (('A', A), ('B', B), ('C', C)):
        q = out(p, 15); g += _t(q[0], q[1] + 5, nm)
    mid = lambda p, q: ((p[0] + q[0]) / 2, (p[1] + q[1]) / 2)
    q = out(mid(C, B), 16); g += _t(q[0], q[1] + 5, la, 'tm')
    q = out(mid(C, A), 16); g += _t(q[0], q[1] + 5, lb, 'tm')
    q = out(mid(A, B), 16); g += _t(q[0], q[1] + 5, lc, 'tx' if not hl else 'tx')
    return fig(W, H_, g)

def fig_right():
    A, C, Bp = (40, 165), (240, 165), (240, 45)
    g = _ln(A, C) + _ln(C, Bp) + _ln(A, Bp, 'acc')
