def _split_wrap(s):
    """Формулы после ". ", ", " и "; " считаем отдельными: неразрывные блоки получаются короче."""
    parts = _re.split(r'([.,;] )', s)
    return ''.join(_wt0(p) if i % 2 == 0 else p for i, p in enumerate(parts))
